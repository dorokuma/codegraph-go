package server

import (
	"github.com/dorokuma/codegraph-go/internal/config"
	"github.com/dorokuma/codegraph-go/internal/extraction"
)

// rgExcludeArgs converts the full directory-exclusion rule set into rg
// negative --glob arguments so rg-based tool paths (search / files /
// callers / callees / impact fallback) do not surface matches from trees
// the indexer itself refuses to walk. The rules come from exactly two
// places — the built-in list (extraction.BuiltinSkipGlobs: skipDirNames,
// skipPathFragments, Go toolchain segments, GOPATH root) and the user
// config (config.ExcludeDirs) — so the rg backstop and the indexer share
// one source of truth instead of a second hardcoded table.
//
// Glob shapes (rg/gitignore semantics). rg anchors a leading "/" glob
// against the child process CWD — callers set cmd.Dir to the project root
// while the search path itself may be a deeper subdirectory, so anchored
// and relative-path rules pin to the top level of the PROJECT tree, not
// the searched subdir. Every rule emits a "!<glob>/" + "!<glob>/**" pair:
// the trailing slash on the first glob gives it gitignore directory
// semantics — it matches the directory itself without matching a plain
// file that happens to share the name — and "/**" covers the contents.
//
//   - bare name "pat"              -> "!pat/",     "!pat/**"
//     excludes a same-named dir at ANY depth, never a same-named file.
//   - fragment "**/a/b"            -> "!**/a/b/",  "!**/a/b/**"
//     excludes the multi-segment path at any depth (root top level and
//     deeper), e.g. .local/lib, go/pkg — without hitting codegraph-go/pkg.
//   - anchored "./sub" / "/sub"    -> "!/sub/",    "!/sub/**"
//     pins the exclusion to <root>/sub and its subtree only — a deep
//     subproj/ref stays searchable. config.ExcludeDirs "a/b" maps the
//     same way because it is already a workdir-relative path.
//   - GOPATH top-level "/go"       -> "!/go/",     "!/go/**"
//     only when <root>/go is a real GOPATH workspace (isGopathRoot), so
//     an ordinary project dir named "go" at top level is not nuked.
//
// User-configured rules are NOT pasted into rg verbatim: every one of them
// goes through extraction.RgExcludeGlob first, which applies the same shape
// mapping as above and escapes what the two glob engines disagree on, so a
// rule the walker reads as a literal directory name ("{foo,bar}", "data[")
// cannot be expanded into other trees — or into an "error parsing glob"
// that kills the whole rg call — on the rg side.
//
// noIgnore=true returns nil: the caller explicitly asked to search inside
// ignored/excluded trees, so no exclusion globs are added.
//
// rg matches these globs against each candidate path RELATIVE to cwd
// (cmd.Dir = project root). A leading "/" in the glob therefore anchors to
// the project root even when the searched path is a subdirectory — a
// narrowed root like /ws/node_modules/pkg is still evaluated relative to
// itself, so ancestor segments that happen to match ("/node_modules/" in
// its own absolute prefix) do NOT blank the narrowed tree.
func rgExcludeArgs(root string, noIgnore bool) []string {
	if noIgnore {
		return nil
	}
	var globs []string
	emit := func(g string) {
		globs = append(globs, "-g", "!"+g+"/", "-g", "!"+g+"/**")
	}
	// Built-in rules: skipDirNames + skipPathFragments + Go toolchain
	// segments, generated by the extraction layer (single source of truth).
	for _, g := range extraction.BuiltinSkipGlobs(root) {
		emit(g)
	}
	// User-configured rules (config.yaml exclude_dirs / CODEGRAPH_EXCLUDE_DIRS).
	// The shape mapping (anchor / bare) and the walker-vs-rg glob escaping
	// both live in extraction.RgExcludeGlob, next to the walker itself, so
	// the two sides cannot drift and no rule can break rg's glob parser.
	for _, pat := range config.ExcludeDirs() {
		// One rule can need TWO globs: the wildcard translation AND a
		// literal translation — see extraction.RgExcludeGlobs (a valid
		// Go pattern like `\{foo` or `[ab]` whose own literal name the
		// pattern does not match is still excluded by the walker's
		// exact-name comparison, so rg needs both forms).
		for _, g := range extraction.RgExcludeGlobs(pat) {
			emit(g)
		}
	}
	return globs
}
